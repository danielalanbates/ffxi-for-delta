def fix_gba_rom(rom_path):
    with open(rom_path, "rb") as f:
        data = bytearray(f.read())

    if len(data) < 0xC0:
        print(f"Error: ROM too small ({len(data)} bytes)", file=sys.stderr)
        return False

    # 1. Ensure Nintendo Logo is exact
    data[0x04:0xA0] = NINTENDO_LOGO

    # 2. Fixed value 0x96 at byte 0xB2
    data[0xB2] = 0x96

    # 3. Calculate Complement Checksum (bytes 0xA0 to 0xBC)
    header_sum = sum(data[0xA0:0xBD])
    checksum = (-(header_sum + 0x19)) & 0xFF
    data[0xBD] = checksum

    # 4. Pad ROM to power of 2 or minimum 64 KB
    min_size = 64 * 1024
    if len(data) < min_size:
        data.extend(b"\x00" * (min_size - len(data)))
    elif len(data) % 4 != 0:
        data.extend(b"\x00" * (4 - (len(data) % 4)))

    with open(rom_path, "wb") as f:
        f.write(data)

    title = data[0xA0:0xAC].decode("latin1", errors="ignore").rstrip("\x00")
    code = data[0xAC:0xB0].decode("latin1", errors="ignore")
    print(f"GBA Header Validated: Title='{title}', Code='{code}', Checksum=0x{checksum:02X}, Size={len(data)} bytes")
    return True

if __name__ == "__main__":
    if len(sys.argv) < 2:
        print("Usage: fix_header.py <rom.gba>")
        sys.exit(1)
    if not fix_gba_rom(sys.argv[1]):
        sys.exit(1)
